#!/usr/bin/env node
// Repair 31 — copy the shared TypeScript engine into the Edge Functions that need it, so the
// server runs the SAME code as the browser (bonus.ts, finance.ts, billingEvents.ts, dealEvents.ts,
// bonusOverview.ts). Copies are GENERATED (never edit them); only import specifiers are rewritten
// for Deno. Run before deploying:  npm run sync:edge
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const lib = resolve(here, '../src/lib')
const fns = resolve(here, '../supabase/functions')

const targets = {
  'my-bonus-overview': ['types', 'finance', 'workHours', 'ilCalendar', 'billingEvents', 'bonus', 'bonusOverview'],
  'recruiter-save-deal': ['types', 'finance', 'workHours', 'ilCalendar', 'billingEvents', 'dealEvents'],
}

const rewrite = (src) =>
  src
    .replace(/from '@\/lib\/supabase'/g, "from './supabase-shim.ts'")
    .replace(/from '@\/lib\/([A-Za-z]+)'/g, "from './$1.ts'")
    .replace(/from '\.\/([A-Za-z]+)'/g, "from './$1.ts'")
    .replace(/from '@supabase\/supabase-js'/g, "from 'npm:@supabase/supabase-js@2'")

const banner = (name) =>
  `// GENERATED by scripts/sync-edge-shared.mjs from src/lib/${name}.ts (Repair 31). Do not edit — edit the source and re-run npm run sync:edge.\n`

for (const [fn, files] of Object.entries(targets)) {
  const dir = resolve(fns, fn, 'lib')
  mkdirSync(dir, { recursive: true })
  for (const f of files) {
    writeFileSync(resolve(dir, `${f}.ts`), banner(f) + rewrite(readFileSync(resolve(lib, `${f}.ts`), 'utf8').replace(/\r\n/g, '\n')))
  }
  // billingEvents.ts imports the browser supabase singleton for its DB helpers; the server
  // path never calls them (it only uses the pure generators), so a stub keeps the module loadable.
  writeFileSync(resolve(dir, 'supabase-shim.ts'), '// stub — see scripts/sync-edge-shared.mjs\nexport const supabase = undefined as never\n')
  console.log('synced', fn, files.join(','))
}
